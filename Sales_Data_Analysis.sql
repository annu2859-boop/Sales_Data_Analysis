#Find the customers whose spending has increased compared to their previous order
select*from(select c.customer_id,c.customer_name, o.order_date,
        o.order_id,sum(oi.quantity*oi.unit_price)as spending,
lag(sum(oi.quantity*oi.unit_price)) over( partition by c.customer_id order by o.order_date,o.order_id)as previous_spending 
from customers as c join orders as o on
c.customer_id=o.customer_id join order_items as oi on
o.order_id=oi.order_id group by c.customer_id,c.customer_name,o.order_id,
        o.order_date)as tt
where spending>previous_spending;

