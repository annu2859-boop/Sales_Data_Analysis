#Find customers and classify them into three groups based on their total spending:
#haigh value equal and greater than 100000
#medium value 50000 and 100000 
#low value 50000
select c.customer_name,sum(oi.quantity*oi.unit_price)as total_spending,
case when sum(oi.quantity*oi.unit_price)>=100000 then "high"
      when  sum(oi.quantity*oi.unit_price) between 50000 and 100000 then "medium"
      when   sum(oi.quantity*oi.unit_price)<50000 then "low value" 
      END AS customer_segment
from customers as c join orders as o on
c.customer_id=o.customer_id join order_items as oi on
o.order_id=oi.order_id group by c.customer_name;

#Find the customers who have placed the maximum number of orders.
with customer_orders as (
    select c.customer_id, c.customer_name,
           count(o.order_id) as total_orders
    from customers c
    join orders o
        on c.customer_id = o.customer_id
    group by c.customer_id, c.customer_name
),
ranked_customers as (
    select*,
           dense_rank() OVER(
               order by total_orders DESC
           ) AS rnk
    from customer_orders
)
select *
from ranked_customers
where rnk = 1;

