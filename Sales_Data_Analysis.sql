o.order_id=oi.order_id group by c.customer_id,c.customer_name  having total_spending<50000;

#Find the customers who have placed more than 2 orders.
select c.customer_id,c.customer_name,count(o.order_id) from customers as c join
orders as o on c.customer_id=o.customer_id group by c.customer_id,c.customer_name having count(o.order_id)>2;

#Find the top 5 products based on total quantity sold.
select p.product_id,p.product_name,sum(oi.quantity)as total_quantity from products as p join order_items as oi on
p.product_id=oi.product_id group by p.product_id,p.product_name order by total_quantity desc limit 5;

